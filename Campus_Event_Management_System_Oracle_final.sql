CREATE TABLE Students (
    student_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name   VARCHAR2(80) NOT NULL,
    email          VARCHAR2(100) NOT NULL UNIQUE,
    department     VARCHAR2(60) NOT NULL,
    semester       NUMBER(2) CHECK (semester BETWEEN 1 AND 8)
);

CREATE TABLE Venues (
    venue_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name     VARCHAR2(100) NOT NULL UNIQUE,
    location       VARCHAR2(120),
    capacity        NUMBER(5) NOT NULL CHECK (capacity > 0)
);

CREATE TABLE Events (
    event_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name     VARCHAR2(120) NOT NULL,
    event_date     DATE NOT NULL,
    event_type     VARCHAR2(40),
    venue_id       NUMBER NOT NULL,
    max_capacity   NUMBER(5) NOT NULL CHECK (max_capacity > 0),
    CONSTRAINT fk_event_venue FOREIGN KEY (venue_id)
        REFERENCES Venues(venue_id)
);

CREATE TABLE Registrations (
    registration_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    event_id        NUMBER NOT NULL,
    registration_date DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_reg_student FOREIGN KEY (student_id)
        REFERENCES Students(student_id),
    CONSTRAINT fk_reg_event FOREIGN KEY (event_id)
        REFERENCES Events(event_id),
    CONSTRAINT uq_student_event UNIQUE (student_id, event_id)
);

CREATE TABLE Attendance (
    attendance_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id NUMBER NOT NULL UNIQUE,
    present        CHAR(1) DEFAULT 'N' CHECK (present IN ('Y','N')),
    marked_on      DATE,
    CONSTRAINT fk_att_registration FOREIGN KEY (registration_id)
        REFERENCES Registrations(registration_id)
);

