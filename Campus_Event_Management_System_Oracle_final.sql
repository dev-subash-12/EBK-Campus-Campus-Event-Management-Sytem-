CREATE OR REPLACE FUNCTION Available_Seats(p_event_id IN NUMBER)
RETURN NUMBER
IS
    v_capacity NUMBER;
    v_registered NUMBER;
BEGIN
    SELECT max_capacity INTO v_capacity
    FROM Events WHERE event_id = p_event_id;

    SELECT COUNT(*) INTO v_registered
    FROM Registrations WHERE event_id = p_event_id;

    RETURN v_capacity - v_registered;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
END;
/

CREATE OR REPLACE PROCEDURE Register_Student(
    p_student_id IN NUMBER,
    p_event_id   IN NUMBER
)
IS
    v_seats NUMBER;
    v_registration_id NUMBER;
BEGIN
    SELECT max_capacity INTO v_seats
    FROM Events
    WHERE event_id = p_event_id
    FOR UPDATE;

    v_seats := Available_Seats(p_event_id);

    IF v_seats <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Event is full or unavailable.');
    END IF;

    INSERT INTO Registrations (student_id, event_id)
    VALUES (p_student_id, p_event_id)
    RETURNING registration_id INTO v_registration_id;

    INSERT INTO Attendance (registration_id, present)
    VALUES (v_registration_id, 'N');

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Registration successful. ID: ' || v_registration_id);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Student is already registered for this event.');
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20003, 'Student or event ID does not exist.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE TRIGGER Check_Event_Capacity
BEFORE INSERT ON Registrations
FOR EACH ROW
DECLARE
    v_capacity NUMBER;
    v_count NUMBER;
BEGIN
    SELECT max_capacity INTO v_capacity
    FROM Events WHERE event_id = :NEW.event_id;

    SELECT COUNT(*) INTO v_count
    FROM Registrations WHERE event_id = :NEW.event_id;

    IF v_count >= v_capacity THEN
        RAISE_APPLICATION_ERROR(-20004, 'Registration limit reached.');
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE Event_Summary
IS
    CURSOR event_cur IS
        SELECT e.event_id, e.event_name, COUNT(r.registration_id) AS total
        FROM Events e
        LEFT JOIN Registrations r ON e.event_id = r.event_id
        GROUP BY e.event_id, e.event_name
        ORDER BY e.event_id;
BEGIN
    FOR rec IN event_cur LOOP
        DBMS_OUTPUT.PUT_LINE(
            rec.event_name || ' | Registrations: ' || rec.total
        );
    END LOOP;
END;
/

CREATE OR REPLACE PROCEDURE Mark_Attendance(
    p_registration_id IN NUMBER,
    p_present IN CHAR
)
IS
BEGIN
    IF p_present NOT IN ('Y','N') THEN
        RAISE_APPLICATION_ERROR(-20005, 'Attendance must be Y or N.');
    END IF;

    UPDATE Attendance
    SET present = p_present, marked_on = SYSDATE
    WHERE registration_id = p_registration_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20006, 'Registration ID not found.');
    END IF;

    COMMIT;
END;
/

